let statsCountRaf = 0;
const countUpPlayed = {};

function countUpFormat(el, n){
  const prefix = el.getAttribute('data-count-prefix') || '';
  const suffix = el.getAttribute('data-count-suffix') || '';
  const decimals = Number(el.getAttribute('data-count-decimals') || 0);
  const val = decimals > 0 ? Number(n).toFixed(decimals) : Math.round(n).toLocaleString('en-US');
  return prefix + val + suffix;
}

function countUpFrom(el){
  const raw = el.getAttribute('data-count-from');
  return raw == null || raw === '' ? 0 : Number(raw);
}

function snapCountUp(nodes){
  nodes.forEach(el => { el.textContent = countUpFormat(el, Number(el.dataset.countTo)); });
}

function runCountUp(group){
  if (statsCountRaf) cancelAnimationFrame(statsCountRaf);
  statsCountRaf = 0;
  const nodes = Array.from(document.querySelectorAll('#slideHtmlCanvas [data-count-to]'));
  if (!nodes.length) return;
  const reduce = !!(window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches);
  if (reduce || countUpPlayed[group] || deckExporting){
    snapCountUp(nodes);
    return;
  }
  countUpPlayed[group] = true;
  nodes.forEach(el => { el.textContent = countUpFormat(el, countUpFrom(el)); });
  const duration = 520;
  const stagger = 40;
  const ease = t => 1 - Math.pow(1 - t, 3);
  const t0 = performance.now();
  const tick = now => {
    let running = false;
    nodes.forEach((el, i) => {
      const p = Math.min(1, Math.max(0, (now - (t0 + i * stagger)) / duration));
      const from = countUpFrom(el);
      const to = Number(el.dataset.countTo);
      el.textContent = countUpFormat(el, from + (to - from) * ease(p));
      if (p < 1) running = true;
    });
    statsCountRaf = running ? requestAnimationFrame(tick) : 0;
  };
  statsCountRaf = requestAnimationFrame(tick);
}

function animateTangibleStatsSlide(){ runCountUp('stats'); }
function animateKeyConsiderationsSlide(){ runCountUp('kc'); }
function animateStrategyDeepDiveCount(){ runCountUp('sdd'); }
